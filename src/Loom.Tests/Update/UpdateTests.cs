/// <summary>P2-3：SHA256SUMS.txt 的解析（多格式、文件名匹配）。</summary>
public sealed class ChecksumManifestTests
{
    private const string Hash = "0123456789abcdef0123456789abcdef0123456789abcdef0123456789abcdef";

    [Theory]
    [InlineData(Hash + "  loom-dsh-Setup.exe")]
    [InlineData(Hash + " *loom-dsh-Setup.exe")]
    [InlineData(Hash + "  ./dist/loom-dsh-Setup.exe")]
    [InlineData("loom-dsh-Setup.exe  " + Hash)]
    [InlineData("LOOM-DSH-SETUP.EXE 0123456789ABCDEF0123456789ABCDEF0123456789ABCDEF0123456789ABCDEF")]
    public void FindsEntryInCommonFormats(string line)
    {
        Assert.Equal(Hash, ChecksumManifest.FindSha256(line + Environment.NewLine, "loom-dsh-Setup.exe"));
    }

    [Fact]
    public void IgnoresCommentsAndOtherFiles()
    {
        var manifest = "# generated by publish\n"
                       + Hash + "  other-file.exe\n"
                       + Hash + "  loom-dsh-Setup.exe\n";
        Assert.Equal(Hash, ChecksumManifest.FindSha256(manifest, "loom-dsh-Setup.exe"));
        Assert.Null(ChecksumManifest.FindSha256(manifest, "missing.exe"));
        Assert.Null(ChecksumManifest.FindSha256("", "loom-dsh-Setup.exe"));
        Assert.Null(ChecksumManifest.FindSha256(null, "loom-dsh-Setup.exe"));
    }

    [Fact]
    public void ComputesLowercaseHexOfFile()
    {
        var path = Path.Combine(Path.GetTempPath(), "loom-update-tests", Guid.NewGuid().ToString("N") + ".bin");
        Directory.CreateDirectory(Path.GetDirectoryName(path)!);
        try
        {
            File.WriteAllText(path, "abc");
            // SHA256("abc")
            Assert.Equal(
                "ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad",
                ChecksumManifest.ComputeFileSha256(path));
        }
        finally
        {
            try
            {
                File.Delete(path);
            }
            catch
            {
                // best effort
            }
        }
    }
}

/// <summary>State machine / local-source end-to-end (no network): check → download → cleanup.</summary>
public sealed class UpdateServiceTests : IDisposable
{
    private const long MinimumAssetBytes = 1024 * 1024;

    /// <summary>
    /// 比当前工具版本（<see cref="LoomPaths.ToolVersion"/>）更高的版本号：
    /// 版本号提升时（例如 0.1.1 → 0.2.0）这些“有更新版本可用”的用例不用再改。
    /// </summary>
    private static readonly (string Tag, string Version) Newer = BuildNewer();

    private static (string Tag, string Version) BuildNewer()
    {
        var major = SemVersion.TryParse(LoomPaths.ToolVersion, out var current) ? current.Major + 1 : 1;
        var version = major + ".0.0";
        return ("v" + version, version);
    }

    private readonly string _root;
    private readonly LoomPaths _paths;
    private readonly LoomConfig _config = new()
    {
        AutoCheckUpdate = true,
        DeleteSetupAfterUpdate = true,
    };

    public UpdateServiceTests()
    {
        _root = Path.Combine(Path.GetTempPath(), "loom-update-tests", Guid.NewGuid().ToString("N"));
        Directory.CreateDirectory(_root);
        _paths = new LoomPaths(Path.Combine(_root, "data"));
        _paths.EnsureDirectories();
    }

    public void Dispose()
    {
        try
        {
            Directory.Delete(_root, recursive: true);
        }
        catch
        {
            // best effort: temp directory
        }
    }

    private UpdateService CreateService(bool installed = true, string? installDir = null)
    {
        installDir ??= Path.Combine(_root, "install-" + Guid.NewGuid().ToString("N"));
        Directory.CreateDirectory(installDir);
        if (installed) File.WriteAllText(Path.Combine(installDir, "unins000.exe"), "");
        var service = new UpdateService(_paths, () => _config, _ => { });
        service.InstallInfo = AppInstallInfo.ForDirectory(installDir);
        service.DownloadPathOverride = DownloadPath;
        return service;
    }

    private string CreateSourceAsset(long bytes = MinimumAssetBytes * 2)
    {
        var source = Path.Combine(_root, "source-" + Guid.NewGuid().ToString("N"));
        Directory.CreateDirectory(source);
        var asset = Path.Combine(source, AppInstallInfo.SetupAssetName);
        File.WriteAllBytes(asset, new byte[bytes]);
        return source;
    }

    /// <summary>本地源 + SHA256SUMS.txt（<paramref name="hashOverride"/> 用于构造校验失败）。</summary>
    private string CreateSourceAssetWithChecksums(string? hashOverride = null)
    {
        var source = CreateSourceAsset();
        var asset = Path.Combine(source, AppInstallInfo.SetupAssetName);
        var hash = hashOverride ?? ChecksumManifest.ComputeFileSha256(asset);
        File.WriteAllText(
            Path.Combine(source, "SHA256SUMS.txt"),
            hash + "  " + AppInstallInfo.SetupAssetName + Environment.NewLine);
        return source;
    }

    private string DownloadPath => Path.Combine(_root, "downloads", AppInstallInfo.SetupAssetName);

